-- 0001_users: one row per person who can log in, patient or doctor.
-- Django repeated these account columns in "Patients_patient" and "Doctor_doctor";
-- here they live once and the profile tables (0002) point at them.

CREATE TABLE users (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role        VARCHAR(10)  NOT NULL,
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(254) NOT NULL,
  password    VARCHAR(255),
  phone       VARCHAR(20),
  is_active   BOOLEAN      NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT users_role_check CHECK (role IN ('patient', 'doctor')),
  -- Django had UNIQUE(email) separately in each table, so a doctor and a
  -- patient may share an address. Case-sensitive, exactly like Django's lookup.
  CONSTRAINT users_email_role_key UNIQUE (email, role),
  -- Redundant with the primary key on its own; it exists so profile tables can
  -- reference (id, role) and the database guarantees a patient profile points
  -- at a 'patient' user and a doctor profile at a 'doctor' user.
  CONSTRAINT users_id_role_key UNIQUE (id, role),
  -- Doctor.password was NOT NULL in Django; Patient.password was nullable.
  CONSTRAINT users_doctor_password_check CHECK (role <> 'doctor' OR password IS NOT NULL)
);

COMMENT ON TABLE users IS
  'Login identity shared by patients and doctors. Profile data lives in patients / doctors (1:1 via user_id).';
COMMENT ON COLUMN users.role IS
  'patient or doctor. Paired with id in a UNIQUE so profile tables can enforce the role through a composite foreign key.';
COMMENT ON COLUMN users.email IS
  'Stored exactly as received (no lower-casing), as Django did. Login lower-cases its input, so mixed-case emails cannot log in.';
COMMENT ON COLUMN users.password IS
  'Django-format hash (pbkdf2_sha256$<iterations>$<salt>$<hash>). NULL is allowed for patients: patient login is email-only.';
COMMENT ON COLUMN users.created_at IS
  'Django default=timezone.now. Copied as-is by the ETL, so it can be later than updated_at for rows that predate the column.';
COMMENT ON COLUMN users.updated_at IS
  'Django auto_now: every UPDATE must set updated_at = now() explicitly.';
