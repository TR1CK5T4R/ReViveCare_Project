-- 0005_reports: medical documents attached to a patient.

CREATE TABLE patient_reports (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id             BIGINT       NOT NULL,
  report_type            VARCHAR(20)  NOT NULL,
  title                  VARCHAR(200) NOT NULL,
  description            TEXT,
  file_url               VARCHAR(200),
  uploaded_by_doctor_id  BIGINT,
  created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT patient_reports_report_type_check
    CHECK (report_type IN ('lab', 'imaging', 'discharge', 'prescription', 'other')),
  CONSTRAINT patient_reports_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE,
  CONSTRAINT patient_reports_uploaded_by_doctor_fkey FOREIGN KEY (uploaded_by_doctor_id)
    REFERENCES doctors (id) ON DELETE SET NULL
);

COMMENT ON TABLE patient_reports IS
  'Django Patients.PatientReport. No endpoint reads or writes it today. Django Meta.ordering = -created_at.';
COMMENT ON COLUMN patient_reports.file_url IS
  'Django URLField: VARCHAR(200), URL format validated only by Django forms, not by the database.';
COMMENT ON COLUMN patient_reports.uploaded_by_doctor_id IS
  'Django column uploaded_by_id.';
