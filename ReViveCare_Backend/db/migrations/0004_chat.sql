-- 0004_chat: stored chat messages between a patient and the AI assistant.

CREATE TABLE chat_messages (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id         BIGINT           NOT NULL,
  sender             VARCHAR(10)      NOT NULL,
  message            TEXT             NOT NULL,
  language           VARCHAR(10)      NOT NULL DEFAULT 'english',
  seriousness_score  DOUBLE PRECISION NOT NULL DEFAULT 0.0,
  sent_at            TIMESTAMPTZ      NOT NULL DEFAULT now(),

  CONSTRAINT chat_messages_sender_check CHECK (sender IN ('patient', 'ai')),
  CONSTRAINT chat_messages_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE
);

COMMENT ON TABLE chat_messages IS
  'Django Patients.ChatMessage. Kept for future use only: the live chat keeps its history in the session (chat_history, max 20 items), not here. Django Meta.ordering = timestamp (sent_at).';
COMMENT ON COLUMN chat_messages.language IS
  'Free text in Django (''english'' or ''hindi'' in practice), so no CHECK constraint.';
COMMENT ON COLUMN chat_messages.seriousness_score IS
  'AI-assessed severity clamped to [0.0, 1.0]. A score > 0.75 triggers the doctor alert.';
COMMENT ON COLUMN chat_messages.sent_at IS
  'Django column "timestamp", renamed because it is a vague name and an SQL type keyword.';
