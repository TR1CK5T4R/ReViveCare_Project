-- 0003_exercise: exercise catalogue and recorded exercise sessions.

CREATE TABLE exercise_types (
  code  VARCHAR(50)  PRIMARY KEY,
  name  VARCHAR(100) NOT NULL
);

COMMENT ON TABLE exercise_types IS
  'Lookup of known exercises. Django stored exercise_type as free text; the codes are the ids the React app sends (ExerciseSelection.jsx).';

