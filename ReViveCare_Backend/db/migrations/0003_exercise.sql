CREATE TABLE exercise_sessions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id      BIGINT           NOT NULL,
  exercise_type   VARCHAR(50)      NOT NULL,
  start_time      TIMESTAMPTZ      NOT NULL DEFAULT now(),
  end_time        TIMESTAMPTZ,
  target_reps     INTEGER          NOT NULL DEFAULT 12,
  excellent_reps  INTEGER          NOT NULL DEFAULT 0,
  good_reps       INTEGER          NOT NULL DEFAULT 0,
  partial_reps    INTEGER          NOT NULL DEFAULT 0,
  completed_reps  INTEGER GENERATED ALWAYS AS (good_reps + partial_reps) STORED,
  accuracy_score  DOUBLE PRECISION NOT NULL DEFAULT 0.0,
  notes           TEXT,

  CONSTRAINT exercise_sessions_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE,
  CONSTRAINT exercise_sessions_exercise_type_fkey FOREIGN KEY (exercise_type)
    REFERENCES exercise_types (code)
);

COMMENT ON TABLE exercise_sessions IS
  'One workout (Django Patients.ExerciseSession). Django never wrote this table; the browser-tracking contract will. Django Meta.ordering = -start_time.';
COMMENT ON COLUMN exercise_sessions.good_reps IS
  'Includes excellent reps, as in the Django rep logic (every excellent rep also increments good).';
COMMENT ON COLUMN exercise_sessions.completed_reps IS
  'Derived: in the Django rep logic every rep increments exactly one of good_reps or partial_reps, so the total is their sum. Computed by Postgres, never written.';
COMMENT ON COLUMN exercise_sessions.accuracy_score IS
  'Percentage. Django has no formula for it anywhere, so it is stored, not derived.';
COMMENT ON COLUMN exercise_sessions.end_time IS
  'NULL while the session is in progress or if it was abandoned.';
