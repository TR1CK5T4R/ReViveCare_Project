-- 0002_patients_doctors: the profile tables, one row per user of that role.
-- Their ids are the ids Django used ("Doctor_doctor".id, "Patients_patient".id),
-- because patients.id is exposed by the API and stored in the session.

CREATE TABLE doctors (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT      NOT NULL,
  user_role       VARCHAR(10) NOT NULL DEFAULT 'doctor',
  specialty       VARCHAR(100),
  license_number  VARCHAR(50) NOT NULL,

  CONSTRAINT doctors_user_id_key UNIQUE (user_id),
  CONSTRAINT doctors_license_number_key UNIQUE (license_number),
  CONSTRAINT doctors_user_role_check CHECK (user_role = 'doctor'),
  CONSTRAINT doctors_user_fkey FOREIGN KEY (user_id, user_role)
    REFERENCES users (id, role) ON DELETE CASCADE
);

COMMENT ON TABLE doctors IS
  'Doctor profile (Django Doctor.Doctor). Name, email, password, phone, is_active and timestamps are on users. Django Meta.ordering = -created_at (users.created_at).';
COMMENT ON COLUMN doctors.id IS
  'Same value as Django "Doctor_doctor".id.';
COMMENT ON COLUMN doctors.user_role IS
  'Always ''doctor''. Exists only so the composite foreign key (user_id, user_role) can reject links to a patient user.';

CREATE TABLE patients (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             BIGINT      NOT NULL,
  user_role           VARCHAR(10) NOT NULL DEFAULT 'patient',
  age                 INTEGER,
  gender              VARCHAR(1),
  address             TEXT,
  info                TEXT        NOT NULL,
  assigned_doctor_id  BIGINT,

  CONSTRAINT patients_user_id_key UNIQUE (user_id),
  CONSTRAINT patients_user_role_check CHECK (user_role = 'patient'),
  -- Django choices M/F/O; every existing row is NULL, so the CHECK is safe.
  CONSTRAINT patients_gender_check CHECK (gender IN ('M', 'F', 'O')),
  CONSTRAINT patients_user_fkey FOREIGN KEY (user_id, user_role)
    REFERENCES users (id, role) ON DELETE CASCADE,
  CONSTRAINT patients_assigned_doctor_fkey FOREIGN KEY (assigned_doctor_id)
    REFERENCES doctors (id) ON DELETE SET NULL
);

COMMENT ON TABLE patients IS
  'Patient profile (Django Patients.Patient). Account columns are on users. Django Meta.ordering = -updated_at (users.updated_at).';
COMMENT ON COLUMN patients.id IS
  'Same value as Django "Patients_patient".id. Returned by /patient/dashboard/ and stored in the session as patient_id.';
COMMENT ON COLUMN patients.user_role IS
  'Always ''patient''. Exists only so the composite foreign key (user_id, user_role) can reject links to a doctor user.';
COMMENT ON COLUMN patients.info IS
  'Medical history / surgery details written by the doctor. Django declared max_length=3000 but never enforced it, so there is no length limit here.';
COMMENT ON COLUMN patients.assigned_doctor_id IS
  'Django ForeignKey(on_delete=SET_NULL). No endpoint sets it today.';
