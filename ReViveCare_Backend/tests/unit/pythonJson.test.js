import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { pyFloatRepr, pyJsonLoads, pyStrRepr, PythonError } from '../../src/utils/pythonJson.js';
import { readDoctorInfoFields } from '../../src/services/doctor.service.js';

// Produced by Python 3.12 (Unicode 15.0) in the Django venv: parity-tools/golden/doctor_info.py
const golden = JSON.parse(readFileSync(new URL('../fixtures/doctor_info_golden.json', import.meta.url), 'utf8'));

/** What our port does with a body: the three strings, or the Python exception name. */
function nodeOutcome(bytes) {
  try {
    return readDoctorInfoFields(pyJsonLoads(bytes));
  } catch (err) {
    if (err instanceof PythonError) return { error: err.pyType };
    throw err;
  }
}

describe('doctor_info body → stored strings (R-DOC-01, golden)', () => {
  it(`was generated by Python ${golden.python}`, () => {
    expect(golden.cases.length).toBeGreaterThan(100);
  });

  it.each(golden.cases.map((c) => [Buffer.from(c.body, 'hex').toString('latin1').slice(0, 70), c]))(
    '%j',
    (_label, { body, outcome }) => {
      expect(nodeOutcome(Buffer.from(body, 'hex'))).toEqual(outcome);
    },
  );
});
